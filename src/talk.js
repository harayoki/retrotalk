// 音声を合成します。
//
// 実機は 10ms のフレームごとにしか値を更新できず、1 回に動かせる幅も
// 決まっていました。声のたどたどしさは、音質の粗さではなく、
// この窮屈さから出ています。
//
//   音源（インパルスまたはノイズ） -> 2 次 IIR フィルタ 5 段（直列） -> 出来上がり
//
// 破裂音は、本体が 10ms しかなく、カ行とタ行とパ行の違いを伝えているのは
// その前後で舌や唇が動く音のほうです。閉じているあいだに舌を持ち場へ動かし、
// 開いたあとは息を漏らすようにしています。

