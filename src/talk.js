/**
 * どの母音が無声化するかを、拍の並び全体から決める。
 *
 * 規則で決まるので辞書は要らない。日本語では `i` `u` が無声子音に挟まれたときと、
 * 無声子音のあとで句が終わるときに、声を出さなくなる。
 *
 *   デス     ス が句末    → 無声化
 *   シタ     シ が sh と t に挟まれる → 無声化
 *   スミ     次が m(声を出す子音)  → しない
 *   デスー   伸ばしている            → しない
 *
 * 続けて 2 つは無声化しない。「シツレイ」で シ も ツ も無声化すると、
 * 声の出ないところが 40ms 続いて言葉が消える。日本語も交互にしか無声化しない。
 *
 * @param {Array} moras `parseTalk()` が返した並び
 * @returns {boolean[]} 拍ごとに、無声化するかどうか
 */
/**
 * 言い切る記号。語尾の字を張って、少し長くする(`pushBang`)
 * @private
 */
const BANG_MARKS = new Set(['!', '!?']);

/**
 * 語尾で高さが上がる記号。そこは無声化させない(上がりが聞こえなくなる)
 * @private
 */
const LIFT_MARKS = new Set(['!', '?', '!?']);

function markDevoiced(moras) {
  const out = moras.map(() => false);
  let prev = -1;                      // 直前に声を出した拍の番号
  let phrase = [];                    // いまの句で、声を出す拍の番号
  /**
   * 句にひとつも声が残らないなら、最後のひとつは無声化しない。
   * 「シュ。」「シ。」のように 1 拍だけの文だと、規則どおりに無声化すると
   * 文まるごとが息だけになる。実際「ささやきに聞こえる」と言われた
   * (2026-09-03)。人もそういう言い方はしない
   */
  const keepOne = () => {
    if (!phrase.length || phrase.some((k) => !out[k])) return;
    out[phrase[phrase.length - 1]] = false;
  };
  for (let i = 0; i < moras.length; i++) {
    const m = moras[i];
    if (m.set || m.tune) continue;    // 長さを持たない指示は飛ばす
    if (m.pause) { keepOne(); phrase = []; prev = -1; continue; }
    const was = prev; prev = i;
    phrase.push(i);
    // 書いてあるとおりにする。記号列(`format: 'aquestalk'`)は
    // どこを無声化するかを書く人が決めているので、規則より記号が強い。
    // 記号が無いところは無声化しない(`devoice: false`)。
    // 書いてあるのに規則で足すと、書いた人の思ったとおりに読まれない
    if (m.devoice !== undefined) { out[i] = !!m.devoice; continue; }
    if (m.v !== 'i' && m.v !== 'u') continue;
    if (m.hold) continue;             // 伸ばす母音は無声化しない
    if (!VOICELESS.has(m.c)) continue;
    // 次に声を出す拍。無ければ句の終わり
    let j = i + 1;
    while (j < moras.length && (moras[j].set || moras[j].tune)) j++;
    const next = moras[j];
    if (next && !next.pause && !VOICELESS.has(next.c)) continue;
    // `！` `？` `！？` の語尾は無声化しない。どれも最後の 1 字で上がるので、
    // そこを息だけにすると上がりを乗せる先が無くなる。
    // 「ゲンキ？」の「キ」が上がっているのに聞こえなかった(2026-09-05)。
    // `！` も上げるようにしたので、同じ扱いにした(2026-09-06)
    if (next && next.pause && LIFT_MARKS.has(next.mark)) continue;
    if (was >= 0 && out[was]) continue;   // 続けて 2 つは無声化しない
    out[i] = true;
  }
  keepOne();
  return out;
}

