  // 子音 4 フレーム・母音 11 フレームのように数えている。
  // `frame` を変えても長さは変わらないようにする — あれは粗さのパラメータで、
  // 動かすと速さまで変わるのでは、読む人には説明のしようがない(2026-09-05)
  const perTick = D.frame / frame;
  const nf = (n) => Math.max(1, Math.round(n * perTick / speed));
  /** 秒で持っているもの(間)は、そのままフレーム数へ */
  const nfSec = (sec) => Math.max(1, Math.round(sec / frame / speed));

